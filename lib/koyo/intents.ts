/**
 * Pre-Checkin Intent Detection
 * ユーザーのメッセージからPre-Checkinモードへの遷移意図を検出する
 */

export function detectPreCheckinIntent(message: string): boolean {
  if (!message || typeof message !== "string") {
    return false;
  }

  const normalizedMessage = message.trim().toLowerCase();

  // Pre-Checkin関連のキーワード
  const preCheckinKeywords = [
    "チェックイン前",
    "到着前",
    "出発地",
    "出発",
    "どこから",
    "どこで",
    "どこへ",
    "出発地点",
    "スタート地点",
    "始まり",
    "最初",
    "到着まで",
    "到着するまで",
    "到着する前に",
    "到着前に",
    "古窯に到着するまで",
    "古窯に到着前に",
    "古窯に到着する前に",
    "古窯へ向かう",
    "古窯へ向かう途中",
    "古窯までの",
    "古窯までの道中",
    "古窯までのルート",
    "古窯までの観光",
    "古窯までのプラン",
    "古窯までの旅",
    "古窯までの旅行",
    "古窯までの観光地",
    "古窯までのスポット",
    "古窯までの見どころ",
    "古窯までの見所",
    "古窯までの観光スポット",
    "古窯までの観光プラン",
    "古窯までの旅行プラン",
    "古窯までの旅プラン",
    "古窯までの観光ルート",
    "古窯までの旅行ルート",
    "古窯までの旅ルート",
    "古窯までの観光コース",
    "古窯までの旅行コース",
    "古窯までの旅コース",
    "古窯までの観光地",
    "古窯までの観光スポット",
    "古窯までの見どころ",
    "古窯までの見所",
    "古窯までの観光地",
    "古窯までの観光スポット",
    "古窯までの見どころ",
    "古窯までの見所",
    "古窯までの観光地",
    "古窯までの観光スポット",
    "古窯までの見どころ",
    "古窯までの見所",
  ];

  // キーワードが含まれているかチェック
  return preCheckinKeywords.some((keyword) => normalizedMessage.includes(keyword));
}

